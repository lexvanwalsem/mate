const dictionaries: Record<Lang, Record<Key, string>> = { en, nl };

let current: Lang = "en";

export const detectLang = (): Lang => (navigator.language.toLowerCase().startsWith("nl") ? "nl" : "en");
export const setLang = (l: Lang) => { current = l; };
export const getLang = () => current;

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return dictionaries[current][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
